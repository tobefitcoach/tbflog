-- 0003: push to the App Store / Play Store app.
--
-- The website's push (push_subscriptions) uses the browser's Push API, which
-- doesn't exist inside the native app. The app instead gets a device token
-- from Apple (and later Google) - one per phone - and the send-push Edge
-- Function sends to those tokens as well as to browser subscriptions.
--
-- device_push_tokens: one row per phone, owned by whoever is signed in on it.
-- claim_push_token(): saves this phone's token for the signed-in user. If the
--   same phone was last used by someone else (shared phone, a log-out that
--   never reached the server), their row is replaced, so a phone only ever
--   gets one person's notifications. A plain upsert can't do that: the old
--   row belongs to another user, so row-level security hides it.
--
-- Safe to run twice.

create table if not exists public.device_push_tokens (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  token text not null unique,
  platform text not null check (platform in ('ios', 'android')),
  updated_at timestamptz not null default now()
);

create index if not exists idx_device_push_tokens_user_id on public.device_push_tokens (user_id);

alter table public.device_push_tokens enable row level security;

drop policy if exists "own device push tokens" on public.device_push_tokens;
create policy "own device push tokens" on public.device_push_tokens
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create or replace function public.claim_push_token(p_token text, p_platform text)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
begin
  if (select auth.uid()) is null then
    raise exception 'Not signed in' using errcode = '42501';
  end if;
  if p_token is null or length(p_token) < 10 or length(p_token) > 4096 then
    raise exception 'Invalid token' using errcode = '22023';
  end if;
  if p_platform not in ('ios', 'android') then
    raise exception 'Invalid platform' using errcode = '22023';
  end if;

  delete from device_push_tokens where token = p_token and user_id <> (select auth.uid());
  insert into device_push_tokens (user_id, token, platform, updated_at)
  values ((select auth.uid()), p_token, p_platform, now())
  on conflict (token) do update set updated_at = now(), platform = excluded.platform;
end;
$function$;

revoke all on function public.claim_push_token(text, text) from public, anon;
grant execute on function public.claim_push_token(text, text) to authenticated;
